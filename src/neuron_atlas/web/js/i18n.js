let lang = 'de';
try {
  const stored = localStorage.getItem(STORAGE);
  if (stored === 'de' || stored === 'en') lang = stored;
} catch {
  lang = 'de';
}

export function getLang() {
  return lang;
}

export function setLang(next) {
  lang = next === 'en' ? 'en' : 'de';
  try {
    localStorage.setItem(STORAGE, lang);
  } catch {
    /* ignore */
  }
  document.documentElement.lang = lang;
}

/**
 * Translate.  `vars` fills {placeholders}; with a [singular, plural] entry, vars.n picks the form.
 * Unknown keys return `fallback` (or the key), so data-driven keys degrade gracefully.
 */
export function t(key, vars, fallback) {
  const entry = S[key];
  if (!entry) return fallback != null ? fallback : key;
  let text = entry[lang === 'en' ? 1 : 0];
  if (Array.isArray(text)) {
    const n = vars && typeof vars.n === 'number' ? vars.n : vars && vars.n != null && /^\d+$/.test(String(vars.n)) ? Number(vars.n) : 2;
    text = n === 1 ? text[0] : text[1];
  }
  if (vars) text = text.replace(/\{(\w+)\}/g, (m, name) => (vars[name] != null ? String(vars[name]) : m));
  return text;
}

export function hasKey(key) {
  return Object.prototype.hasOwnProperty.call(S, key);
}
